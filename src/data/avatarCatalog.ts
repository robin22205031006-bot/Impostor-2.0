const BY_ID = new Map(ALL_CHARACTERS.map((c) => [c.id, c]));

function javaStringHashCode(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  }
  return h;
}

export const AvatarCatalog = {
  all: ALL_CHARACTERS,

  findById(id: string | null | undefined): AvatarCharacter {
    if (id && BY_ID.has(id)) return BY_ID.get(id)!;
    return ALL_CHARACTERS[0];
  },

  defaultForIndex(index: number): AvatarCharacter {
    const safeIdx = ((index % ALL_CHARACTERS.length) + ALL_CHARACTERS.length) % ALL_CHARACTERS.length;
    return ALL_CHARACTERS[safeIdx];
  },

  defaultIdForSeed(seed: string): string {
    const idx = (javaStringHashCode(seed) & 0x7fffffff) % ALL_CHARACTERS.length;
    return ALL_CHARACTERS[idx].id;
  },

  nextAvailableAvatar(usedIds: Set<string>, preferredIndex = 0): AvatarCharacter {
    return ALL_CHARACTERS.find((c) => !usedIds.has(c.id)) ?? this.defaultForIndex(preferredIndex);
  },
};
