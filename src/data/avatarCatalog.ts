export function imageForPose(character: AvatarCharacter, pose: AvatarPose): string {
  switch (pose) {
    case AvatarPose.ORIGINAL:
      return character.baseImage;
    case AvatarPose.ACTION_STANCE:
      return character.actionImage;
    case AvatarPose.TACTICAL_BUST:
      return character.skillImage;
    case AvatarPose.CREST_AURA:
      return character.stanceImage;
  }
}

